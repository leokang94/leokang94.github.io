"""Split the D2Coding webfont into unicode-range slices.

The full D2Coding file is ~1.5MB. Browsers only download an @font-face whose
unicode-range covers a character on the page, so we ship:

- latin:  ASCII, Latin-1, general punctuation (code blocks, English text)
- common: KS X 1001 Hangul (2,350 syllables covering everyday Korean) + CJK symbols
- rest:   the remaining Hangul syllables, rarely downloaded

Outputs woff2 files into public/fonts/ and @font-face rules into
src/styles/fonts.css. Run with: uv run scripts/build-fonts.py
"""

from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "public" / "fonts"
CSS_OUT = ROOT / "src" / "styles" / "fonts.css"

FONTS = [
    # (family, weight, source ttf, file prefix)
    ("D2Coding", 400, "node_modules/@kfonts/d2coding/src/D2Coding.ttf", "d2coding-400"),
]

LATIN = (
    set(range(0x0000, 0x0100))
    | {0x0131, 0x0152, 0x0153, 0x02C6, 0x02DA, 0x02DC, 0x20AC, 0x2122, 0x2212, 0xFEFF, 0xFFFD}
    | set(range(0x2000, 0x2070))
    | set(range(0x2190, 0x2200))
)

HANGUL = set(range(0xAC00, 0xD7A4))


def is_ksx1001(cp: int) -> bool:
    # Python's euc-kr codec also encodes non-KS syllables as 8-byte jamo
    # sequences (KS X 1001 annex 3), so only 2-byte results count.
    try:
        return len(chr(cp).encode("euc-kr")) == 2
    except UnicodeEncodeError:
        return False


COMMON = (
    {cp for cp in HANGUL if is_ksx1001(cp)}
    | set(range(0x3000, 0x3040))  # CJK symbols and punctuation
    | set(range(0x3131, 0x318F))  # Hangul compatibility jamo
    | set(range(0xFF00, 0xFFF0))  # halfwidth / fullwidth forms
)
REST = HANGUL - COMMON

SLICES = [("latin", LATIN), ("common", COMMON), ("rest", REST)]


def to_ranges(cps: set[int]) -> str:
    ordered = sorted(cps)
    ranges: list[str] = []
    start = prev = ordered[0]
    for cp in ordered[1:]:
        if cp == prev + 1:
            prev = cp
            continue
        ranges.append(fmt(start, prev))
        start = prev = cp
    ranges.append(fmt(start, prev))
    return ", ".join(ranges)


def fmt(start: int, end: int) -> str:
    return f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}"


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    CSS_OUT.parent.mkdir(parents=True, exist_ok=True)
    rules: list[str] = []

    for family, weight, src, prefix in FONTS:
        src_path = ROOT / src
        cmap = set(TTFont(src_path).getBestCmap().keys())
        for name, cps in SLICES:
            covered = cps & cmap
            if not covered:
                continue
            out = OUT_DIR / f"{prefix}-{name}.woff2"
            options = subset.Options()
            options.flavor = "woff2"
            options.layout_features = ["*"]
            options.name_IDs = ["*"]
            options.notdef_outline = True
            subsetter = subset.Subsetter(options)
            font = TTFont(src_path)
            subsetter.populate(unicodes=covered)
            subsetter.subset(font)
            font.flavor = "woff2"
            font.save(out)
            print(f"{out.relative_to(ROOT)}  {out.stat().st_size / 1024:.0f}KB  ({len(covered)} glyphs)")
            rules.append(
                "@font-face {\n"
                f"  font-family: '{family}';\n"
                "  font-style: normal;\n"
                f"  font-weight: {weight};\n"
                "  font-display: swap;\n"
                f"  src: url('/fonts/{out.name}') format('woff2');\n"
                f"  unicode-range: {to_ranges(covered)};\n"
                "}\n"
            )

    header = "/* Generated by scripts/build-fonts.py. Do not edit by hand. */\n\n"
    CSS_OUT.write_text(header + "\n".join(rules), encoding="utf-8")
    print(f"{CSS_OUT.relative_to(ROOT)} written")


if __name__ == "__main__":
    main()
